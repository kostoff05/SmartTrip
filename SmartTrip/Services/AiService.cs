        // =====================================================
        // 3. ОРИГИНАЛНАТА GEMINI API ВРЪЗКА
        // =====================================================

        private async Task<string> SendGeminiRequestAsync(
            string prompt)
        {
            try
            {
                // Оригиналният ти Gemini модел и API адрес
                string url =
                    "https://generativelanguage.googleapis.com/v1beta/models/gemini-3.5-flash-lite:generateContent";

                var requestBody = new
                {
                    contents = new[]
                    {
                        new
                        {
                            parts = new[]
                            {
                                new
                                {
                                    text = prompt
                                }
                            }
                        }
                    }
                };

                // Същата сериализация като преди
                string jsonContent =
                    JsonSerializer.Serialize(requestBody);

                using var request = new HttpRequestMessage(
                    HttpMethod.Post, url);

                // Същият начин за изпращане на API ключа
                request.Headers.Add(
                    "X-goog-api-key", _apiKey);

                // Същият тип HTTP съдържание
                request.Content = new StringContent(
                    jsonContent,
                    Encoding.UTF8,
                    "application/json");

                using var response =
                    await _httpClient.SendAsync(request);

                string responseString =
                    await response.Content.ReadAsStringAsync();

                if (!response.IsSuccessStatusCode)
                {
                    return $"Грешка от Gemini API " +
                           $"({response.StatusCode}): " +
                           responseString;
                }

                using var doc =
                    JsonDocument.Parse(responseString);

                // Същата обработка на отговора
                var text = doc.RootElement
                    .GetProperty("candidates")[0]
                    .GetProperty("content")
                    .GetProperty("parts")[0]
                    .GetProperty("text")
                    .GetString();

                return text?.Trim()
                    ?? "Няма генериран отговор.";
            }
            catch (Exception ex)
            {
                return "Възникна грешка при връзка " +
                       "с AI асистента: " + ex.Message;
            }
        }
